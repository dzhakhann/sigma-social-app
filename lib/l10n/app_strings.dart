  static String t(BuildContext context, String key) {
    final lang = AppScope.of(context).lang;
    return _v[lang]?[key] ?? _v['en']?[key] ?? key;
  }

  /// Context-free lookup for services and background code, reading the language
  /// straight off [appConfig]. Prefer `context.t(...)` in widgets — it rebuilds
  /// on a language change, whereas this returns a one-off string.
  ///
  /// Exists so services stop inlining `lang == 'ru' ? '…' : '…'` pairs, which
  /// duplicate strings the dictionary already holds and get missed by the
  /// key-coverage check.
  static String tr(String key) {
    final lang = appConfig.value.lang;
    return _v[lang]?[key] ?? _v['en']?[key] ?? key;
  }
}

extension TrContext on BuildContext {
  String t(String key) => S.t(this, key);
}

// ─── PROFILE ENUM VALUES (gender / relationship) ─────────────────────────────
// New profiles store canonical ids ('male', 'married', …); older rows may hold
// localized strings in either language. Both map to the same id here, so the
// display always follows the current app language.
String canonicalProfileValue(String v) {
  switch (v.trim()) {
    case 'male': case 'Мужской': case 'Male':
      return 'male';
    case 'female': case 'Женский': case 'Female':
      return 'female';
    case 'other_gender': case 'Другое': case 'Other':
      return 'other_gender';
    case 'single': case 'Холост/Не замужем': case 'Single':
      return 'single';
    case 'relationship': case 'В отношениях': case 'In a relationship':
      return 'relationship';
    case 'married': case 'Женат/Замужем': case 'Married':
      return 'married';
    case 'complicated': case 'Всё сложно': case "It's complicated":
      return 'complicated';
    default:
      return v.trim();
  }
}

// Translate known English error strings coming from the backend, so login /
// registration errors follow the app language.
String localizedServerError(BuildContext context, String raw) {
  const map = {
    'Wrong username or password': 'errWrongCreds',
    'Username already taken': 'errUserTaken',
    'Username and password are required': 'fillAll',
    'Username must be at least 3 characters': 'errUserShort',
    'Password must be at least 6 characters': 'passTooShort',
    'Username can only contain letters, numbers, _ and .': 'errUserChars',
    'Too many attempts. Try again later.': 'errTooMany',
    'Wrong username or recovery phrase': 'recoverFailed',
  };
  final key = map[raw.trim()];
  return key != null ? context.t(key) : raw;
}

String localizedProfileValue(BuildContext context, String v) {
  const keys = {
